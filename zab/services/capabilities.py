SURFACES = ("core", "cli", "mcp", "api", "ui")


def _capability(
    *,
    id: str,
    domain: str,
    summary: str,
    risk: str,
    core: str | None,
    cli: str | None,
    mcp: str | None,
    api: str | None,
    ui: str | None,
    status: str,
    parity_notes: str | None = None,
) -> dict[str, Any]:
    payload: dict[str, Any] = {
        "id": id,
        "domain": domain,
        "summary": summary,
        "risk": risk,
        "core": core,
        "cli": cli,
        "mcp": mcp,
        "api": api,
        "ui": ui,
        "status": status,
    }
    if parity_notes:
        payload["parity_notes"] = parity_notes
    return payload


